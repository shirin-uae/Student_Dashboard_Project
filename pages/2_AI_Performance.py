import streamlit as st
import matplotlib.pyplot as plt
from datetime import datetime
# ==========================================
# PERFORMANCE REPORT FUNCTION
# ==========================================

def create_performance_report(
    stream,
    marks,
    overall_marks,
    overall_percentage,
    strongest,
    weakest,
    performance_analysis
):

    report = []

    report.append("=" * 65)
    report.append("              AI ACADEMIC PERFORMANCE REPORT")
    report.append("=" * 65)
    report.append("")

    report.append(f"Stream: {stream}")
    report.append(
        f"Generated on: "
        f"{datetime.now().strftime('%d %B %Y, %I:%M %p')}"
    )

    report.append("")
    report.append("-" * 65)
    report.append("                 SUBJECT-WISE PERFORMANCE")
    report.append("-" * 65)
    report.append("")

    for subject, mark in marks.items():

        subject_percentage = mark

        report.append(
            f"{subject}: {mark:.0f}/100 "
            f"({subject_percentage:.2f}%)"
        )

    report.append("")
    report.append("-" * 65)
    report.append("                    OVERALL RESULT")
    report.append("-" * 65)
    report.append("")

    report.append(
        f"Total Marks: {overall_marks:.0f}/500"
    )

    report.append(
        f"Overall Percentage: {overall_percentage:.2f}%"
    )

    report.append(
        f"Strongest Subject: {strongest[0]} "
        f"({strongest[1]:.0f}/100)"
    )

    report.append(
        f"Weakest Subject: {weakest[0]} "
        f"({weakest[1]:.0f}/100)"
    )

    report.append("")
    report.append("-" * 65)
    report.append("                     AI ANALYSIS")
    report.append("-" * 65)
    report.append("")

    report.append(performance_analysis)

    report.append("")
    report.append(
        f"Recommended Focus: Improve performance in "
        f"{weakest[0]}."
    )

    report.append("")
    report.append("=" * 65)
    report.append("Generated by AI Student Dashboard")
    report.append("=" * 65)

    return "\n".join(report)

# ==========================================
# PAGE SETTINGS
# ==========================================

st.set_page_config(
    page_title="AI Academic Performance Analyzer",
    page_icon="🧠",
    layout="wide"
)

# ==========================================
# TITLE
# ==========================================

st.title("🧠 AI Academic Performance Analyzer")

st.write(
    "Enter your marks below to analyze your academic performance."
)

st.divider()

# ==========================================
# SELECT STREAM
# ==========================================

st.subheader("🎓 Select Your Stream")

stream = st.selectbox(
    "Choose your stream:",
    ["PCMC", "PCMB", "PCBP"]
)

# ==========================================
# SUBJECT NAMES
# ==========================================

if stream == "PCMB":
    subject4 = "Mathematics"
    subject5 = "Biology"

elif stream == "PCMC":
    subject4 = "Mathematics"
    subject5 = "Computer Science"

elif stream == "PCBP":
    subject4 = "Biology"
    subject5 = "Psychology"


# ==========================================
# ENTER MARKS
# ==========================================

st.subheader("📝 Enter Your Marks")

col1, col2 = st.columns(2)

with col1:

    physics = st.number_input(
        "Physics marks (/100)",
        min_value=0.0,
        max_value=100.0,
        value=0.0
    )

    chemistry = st.number_input(
        "Chemistry marks (/100)",
        min_value=0.0,
        max_value=100.0,
        value=0.0
    )

    english = st.number_input(
        "English marks (/100)",
        min_value=0.0,
        max_value=100.0,
        value=0.0
    )

with col2:

    subject4_mark = st.number_input(
        f"{subject4} marks (/100)",
        min_value=0.0,
        max_value=100.0,
        value=0.0
    )

    subject5_mark = st.number_input(
        f"{subject5} marks (/100)",
        min_value=0.0,
        max_value=100.0,
        value=0.0
    )


# ==========================================
# ANALYZE BUTTON
# ==========================================

if st.button(
    "🔍 Analyze Performance",
    use_container_width=True
):

    # Store marks
    marks = {
        "Physics": physics,
        "Chemistry": chemistry,
        subject4: subject4_mark,
        subject5: subject5_mark,
        "English": english
    }

    # ======================================
    # CALCULATE PERCENTAGE
    # ======================================

    percentage = sum(marks.values()) / len(marks)

    # ======================================
    # RANK SUBJECTS
    # ======================================

    ranking = sorted(
        marks.items(),
        key=lambda x: x[1],
        reverse=True
    )

    strongest = ranking[0]
    weakest = ranking[-1]

    # ======================================
    # DISPLAY OVERALL RESULT
    # ======================================

    st.divider()

    st.subheader("📊 Overall Performance")

    col1, col2, col3 = st.columns(3)

    col1.metric(
        "Overall Percentage",
        f"{percentage:.2f}%"
    )

    col2.metric(
        "Strongest Subject",
        strongest[0],
        f"{strongest[1]:.0f}/100"
    )

    col3.metric(
        "Weakest Subject",
        weakest[0],
        f"{weakest[1]:.0f}/100"
    )

    # ======================================
    # SUBJECT RANKING
    # ======================================

    st.subheader("🏆 Subject Ranking")

    for position, (subject, mark) in enumerate(
        ranking,
        start=1
    ):

        st.write(
            f"**{position}. {subject} — {mark:.0f}/100**"
        )

        st.progress(
            int(mark)
        )

    # ======================================
    # AI ANALYSIS
    # ======================================

    st.subheader("🤖 AI Analysis")

    if percentage >= 90:

        performance_analysis = (
            "Exceptional academic performance! "
            "You are demonstrating excellent understanding "
            "across your subjects."
        )

        st.success(performance_analysis)

    elif percentage >= 80:

        performance_analysis = (
            "Excellent academic performance! "
            "You have a strong academic foundation."
        )

        st.success(performance_analysis)

    elif percentage >= 70:

        performance_analysis = (
            "Good academic performance. "
            "With consistent effort, you can improve "
            "your results further."
        )

        st.info(performance_analysis)

    else:

        performance_analysis = (
            "Your performance needs improvement. "
            "Focus on strengthening your weaker subjects."
        )

        st.warning(performance_analysis)

    st.write(
        f"🎯 **Recommended focus:** Improve your performance in "
        f"**{weakest[0]}**."
    )
    

    # ======================================
    # PIE CHART
    # ======================================

    st.subheader("📈 Subject Performance Distribution")

    subjects = list(marks.keys())
    scores = list(marks.values())

    fig, ax = plt.subplots(
        figsize=(7, 7)
    )

    ax.pie(
        scores,
        labels=subjects,
        autopct="%1.1f%%"
    )

    ax.set_title(
        "Subject Performance Distribution"
    )

    st.pyplot(fig)

    plt.close(fig)

    # ======================================
    # EXPORT PERFORMANCE REPORT
    # ======================================

    st.divider()

    st.subheader("📄 Performance Report")

    overall_marks = sum(marks.values())

    performance_report = create_performance_report(
        stream=stream,
        marks=marks,
        overall_marks=overall_marks,
        overall_percentage=percentage,
        strongest=strongest,
        weakest=weakest,
        performance_analysis=performance_analysis
    )

    col1, col2 = st.columns(2)

    with col1:

        st.download_button(
            label="⬇️ Download Performance Report",
            data=performance_report,
            file_name="AI_Performance_Report.txt",
            mime="text/plain",
            use_container_width=True
        )

    with col2:

        if st.button(
            "🖨️ Print Performance Report",
            use_container_width=True
        ):

            st.info(
                "Use your browser's Print option "
                "(Ctrl+P / Cmd+P) to print the report."
            )
