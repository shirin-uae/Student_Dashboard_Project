def load_tasks():
    rows = run_query(
        """
        SELECT id, subject, topic, duration, priority,
               deadline, study_date, added_on, completed
        FROM study_tasks
        WHERE student_id = %s
        ORDER BY id
        """,
        (STUDENT_ID,),
        dictionary=True,
        fetch=True
    )

    return [
        {
            "id": r["id"],
            "Subject": r["subject"],
            "Topic": r["topic"],
            "Duration": r["duration"],
            "Priority": r["priority"],
            "Deadline": r["deadline"],
            "StudyDate": r["study_date"],
            "Added On": format_datetime(r["added_on"]),
            "Completed": bool(r["completed"])
        }
        for r in rows
    ]


def add_task(subject, topic, duration, priority, deadline):
    run_query(
        """
        INSERT INTO study_tasks
        (student_id, subject, topic, duration, priority,
         deadline, study_date, added_on, completed, xp_awarded)
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, FALSE, FALSE)
        """,
        (
            STUDENT_ID,
            subject,
            topic,
            duration,
            priority,
            deadline,
            datetime.today().date(),
            datetime.now()
        )
    )


def update_completion(task_id, completed):
    run_query(
        """
        UPDATE study_tasks
        SET completed = %s,
            completed_at = CASE
                WHEN %s = TRUE THEN NOW()
                ELSE NULL
            END
        WHERE id = %s AND student_id = %s
        """,
        (completed, completed, task_id, STUDENT_ID)
    )


def update_study_date(task_id, new_date):
    run_query(
        """
        UPDATE study_tasks
        SET study_date = %s
        WHERE id = %s AND student_id = %s
        """,
        (new_date, task_id, STUDENT_ID)
    )

def delete_task(task, row):
    run_query(
        """
        INSERT INTO deleted_tasks
        (student_id, task_id, subject, topic, duration, priority,
         deadline, study_date, added_on, row_date, start_time,
         end_time, row_duration, row_deadline)
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
        """,
        (
            STUDENT_ID,
            task["id"],
            task["Subject"],
            task["Topic"],
            task["Duration"],
            task["Priority"],
            task["Deadline"],
            task["StudyDate"],
            parse_datetime(
                task["Added On"],
                "%Y-%m-%d %H:%M",
                datetime.now()
            ),
            datetime.strptime(
                row["Date"],
                "%Y-%m-%d"
            ).date(),
            row["Start"],
            row["End"],

            # Store numeric duration in MySQL
            task["Duration"],

            datetime.strptime(
                row["Deadline"],
                "%Y-%m-%d"
            ).date()
        )
    )

    run_query(
        """
        DELETE FROM study_tasks
        WHERE id = %s AND student_id = %s
        """,
        (task["id"], STUDENT_ID)
    )
    


