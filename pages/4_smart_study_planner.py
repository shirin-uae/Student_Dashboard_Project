def load_preferences():
    rows = run_query(
        """
        SELECT wake_time, sleep_time, break_duration
        FROM study_preferences
        WHERE student_id = %s
        """,
        (STUDENT_ID,),
        dictionary=True,
        fetch=True
    )

    if not rows:
        return {
            "wake": time(7, 0),
            "sleep": time(23, 0),
            "break_block": 10
        }

    r = rows[0]

    return {
        "wake": to_time(r["wake_time"]),
        "sleep": to_time(r["sleep_time"], time(23, 0)),
        "break_block": int(r["break_duration"])
    }


def save_preferences(wake, sleep, break_block):
    run_query(
        """
        INSERT INTO study_preferences
        (student_id, wake_time, sleep_time, break_duration)
        VALUES (%s, %s, %s, %s)
        ON DUPLICATE KEY UPDATE
            wake_time = VALUES(wake_time),
            sleep_time = VALUES(sleep_time),
            break_duration = VALUES(break_duration)
        """,
        (STUDENT_ID, wake, sleep, break_block)
    )


