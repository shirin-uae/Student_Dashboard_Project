def load_deleted():
    rows = run_query(
        """
        SELECT *
        FROM deleted_tasks
        WHERE student_id = %s
        ORDER BY id
        """,
        (STUDENT_ID,),
        dictionary=True,
        fetch=True
    )

    result = []

    for r in rows:
        task = {
            "id": r["task_id"],
            "Subject": r["subject"],
            "Topic": r["topic"],
            "Duration": r["duration"],
            "Priority": r["priority"],
            "Deadline": r["deadline"],
            "StudyDate": r["study_date"],
            "Added On": format_datetime(r["added_on"]),
            "Completed": False
        }

        row = {
            "ID": f"{r['subject']} - {r['topic']}_{r['id']}",
            "Name": f"{r['subject']} - {r['topic']}",
            "Date": format_datetime(r["row_date"], "%Y-%m-%d"),
            "Start": r["start_time"],
            "End": r["end_time"],
            "Duration": r["row_duration"],
            "Deadline": format_datetime(r["row_deadline"], "%Y-%m-%d")
        }

        result.append({
            "deleted_id": r["id"],
            "task": task,
            "row": row
        })

    return result


def restore_task(record):
    task = record["task"]

    run_query(
        """
        INSERT INTO study_tasks
        (student_id, subject, topic, duration, priority,
         deadline, study_date, added_on, completed, xp_awarded)
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, FALSE, FALSE)
        """,
        (
            STUDENT_ID,
            task["Subject"],
            task["Topic"],
            task["Duration"] or 30,
            task["Priority"] or "Medium",
            task["Deadline"] or datetime.today().date(),
            task["StudyDate"] or datetime.today().date(),
            parse_datetime(
                task["Added On"],
                "%Y-%m-%d %H:%M",
                datetime.now()
            )
        )
    )

    run_query(
        """
        DELETE FROM deleted_tasks
        WHERE id = %s AND student_id = %s
        """,
        (record["deleted_id"], STUDENT_ID)
    )


