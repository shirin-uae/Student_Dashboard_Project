def to_time(value, default=time(7, 0)):
    if value is None:
        return default

    if isinstance(value, time):
        return value

    if isinstance(value, timedelta):
        seconds = int(value.total_seconds())
        return time(
            (seconds // 3600) % 24,
            (seconds % 3600) // 60,
            seconds % 60
        )

    if isinstance(value, datetime):
        return value.time()

    if isinstance(value, str):
        for fmt in ("%H:%M:%S", "%H:%M"):
            try:
                return datetime.strptime(value, fmt).time()
            except ValueError:
                pass

    return default


def format_datetime(value, pattern="%Y-%m-%d %H:%M"):
    if value is None:
        return ""

    return value.strftime(pattern)


def parse_datetime(value, pattern, default):
    if not value:
        return default

    try:
        return datetime.strptime(value, pattern)
    except (TypeError, ValueError):
        return default


def run_query(sql, params=(), dictionary=False, fetch=False):
    conn = get_connection()
    cursor = conn.cursor(dictionary=dictionary)

    cursor.execute(sql, params)

    result = cursor.fetchall() if fetch else None

    conn.commit()
    cursor.close()
    conn.close()

    return result


def create_timetable_report(timetable, task_map, selected_date):
    headers = [
        "Date",
        "Start",
        "End",
        "Subject - Topic",
        "Duration",
        "Deadline",
        "Status"
    ]

    widths = [12, 8, 8, 35, 12, 12, 12]

    rows = []

    for entry in timetable:
        task = task_map.get(entry["ID"])

        status = (
            "Completed"
            if task and task["Completed"]
            else "Pending"
        )

        rows.append([
            entry["Date"],
            entry["Start"],
            entry["End"],
            entry["Name"],
            entry["Duration"],
            entry["Deadline"],
            status
        ])

    separator = "+" + "+".join(
        "-" * (width + 2)
        for width in widths
    ) + "+"

    lines = [
        "=" * 100,
        "STUDY TIMETABLE".center(100),
        "=" * 100,
        "",
        f"Date: {selected_date.strftime('%d %B %Y')}",
        "",
        separator
    ]

    header = "|"

    for name, width in zip(headers, widths):
        header += f" {name:<{width}} |"

    lines.append(header)
    lines.append(separator)

    for row in rows:
        data = "|"

        for value, width in zip(row, widths):
            value = str(value)

            if len(value) > width:
                value = value[:width - 3] + "..."

            data += f" {value:<{width}} |"

        lines.append(data)

    lines.extend([
        separator,
        "",
        "=" * 100,
        "Generated by AI Student Dashboard".center(100),
        "=" * 100
    ])

    return "\n".join(lines)


